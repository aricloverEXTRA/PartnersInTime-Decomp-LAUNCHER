def validate() -> None:
    expected = [chr(c) for c in range(FONT_FIRST, FONT_LAST + 1)]
    missing = [c for c in expected if c not in GLYPHS]
    extra = [c for c in GLYPHS if c not in expected]
    if missing:
        raise SystemExit("missing glyphs: " + " ".join(repr(c) for c in missing))
    if extra:
        raise SystemExit("unexpected glyphs: " + " ".join(repr(c) for c in extra))

    for ch, rows in GLYPHS.items():
        if len(rows) != 7:
            raise SystemExit("%r has %d rows, expected 7" % (ch, len(rows)))
        for r, row in enumerate(rows):
            if set(row) - {".", "#"}:
                raise SystemExit("%r row %d has bad cells: %r" % (ch, r, row))
            if len(row) > 5:
                raise SystemExit(
                    "%r row %d is %d cells, max 5 (the 8x8 cell allows 5 ink "
                    "columns plus a 3px gap)" % (ch, r, len(row))
                )


def render() -> str:
    out: list[str] = []
    out.append("# 5x7 pixel font for the Partners in Time patcher UI.")
    out.append("#")
    out.append("# GENERATED by tools/make_font.py - edit the GLYPHS table there,")
    out.append("# not this file. Columns 0-4 carry the ink, 5-7 are the inter-glyph")
    out.append("# gap, and row 7 is a blank baseline so descenders stay clear.")
    out.append("#")
    out.append("# Format: <codepoint> <row0> ... <row6> <blank>")
    out.append("#")
    for code in range(FONT_FIRST, FONT_LAST + 1):
        ch = chr(code)
        rows = GLYPHS[ch]
        cells = [r.ljust(5, ".") for r in rows]
        out.append("%d %s" % (code, " ".join(cells + ["." * GLYPH_W])))
    return "\n".join(out) + "\n"


def main() -> int:
    validate()
    target = pathlib.Path("tools/patch_sources/font8x8.txt")
    target.write_text(render(), encoding="utf-8")
    print("wrote %s (%d glyphs, 0x%02X..0x%02X)"
          % (target, len(GLYPHS), FONT_FIRST, FONT_LAST))
    return 0


if __name__ == "__main__":
    sys.exit(main())
